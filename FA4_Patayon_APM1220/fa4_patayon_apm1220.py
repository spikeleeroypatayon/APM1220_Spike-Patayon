"""For large samples, a simultaneous confidence interval derived from the multivariate normal confidence region is

$$\bar{x}_i \pm \sqrt{\frac{\chi^2_{p, 1-\alpha} \, s_{ii}}{n}}$$

The important idea is that we don't use a separate ordinary 95% interval for every variable because doing that would not preserve 95% simultaneous confidence across all six means.
"""

# (a)
