large_sample_intervals = []

for i in range (p):
  margin = np.sqrt((chi_square_critical * S[i, i]) / n)

  lower = means[i] - margin
  upper = means[i] + margin

  large_sample_intervals.append([lower, upper])

large_sample_intervals = np.array(large_sample_intervals)

