"""**Comparison**. The Bonferroni rectangle is a "box" that ignores the correlation between Weight and Girth, whereas the ellipse's tilt reflects their strong positive correlation. In this case the rectangle corners stick out past the ellipse in some directions (over-covering there) while cutting into the ellipse along its long axis (under-covering the extreme correlated combinations) — visually you should see the rectangle and ellipse overlapping heavily but not coinciding, which is the typical picture: neither region contains the other in general."""

