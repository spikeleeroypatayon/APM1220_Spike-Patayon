"""For reusability, we will create a function for confidence ellipses"""

def confidence_ellipse(mean, covariance, n, critical_value,
                       ax, num_points=500):
    """
    Plot a confidence ellipse satisfying

    n * (mu - mean)' S^{-1} (mu - mean)
        <= critical_value
    """

    # Eigenvalues and eigenvectors of covariance matrix
    eigenvalues, eigenvectors = np.linalg.eigh(covariance)

    # Generate a unit circle
    theta = np.linspace(0, 2*np.pi, num_points)

    circle = np.vstack([
        np.cos(theta),
        np.sin(theta)
    ])

    # Scale matrix
    scale = np.sqrt(critical_value / n)

    transformation = (
        eigenvectors
        @ np.diag(np.sqrt(eigenvalues))
        * scale
    )

    ellipse = transformation @ circle

    ellipse[0, :] += mean[0]
    ellipse[1, :] += mean[1]

    ax.plot(ellipse[0, :], ellipse[1, :])
    ax.scatter(mean[0], mean[1])

    return ax

